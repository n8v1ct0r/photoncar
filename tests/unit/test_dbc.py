# Decoder behavior.


def test_unmapped_short_extended_and_other_bus_frames(toyota: Database) -> None:
    dec = DbcDecoder(toyota, COMMA2K19_TOYOTA_MAPPING, bus=0)
    good = bytes([0x0A, 0x00, 0, 0, 0, 0, 0, 0])
    assert dec.decode(cf(0x123, good)) == []
    assert dec.decode(cf(0x1C4, good, bus=1)) == []
    ext = CanFrame(t_ns=0, bus=0, arb_id=0x1C4, is_ext=True, dlc=8, data=good)
    assert dec.decode(ext) == []
    assert dec.decode(cf(0x1C4, good[:3])) == []
    assert dec.decode_errors == 1
    assert dec.decode(cf(0x1C4, good, t_ns=42)) == [Sample(42, "can.engine_rpm", 2000.0)]
    assert dec.frame_ids == frozenset({0x1C4, 0xAA, 0x25})


def test_mapping_errors_are_refused(toyota: Database, bmw: Database) -> None:
    with pytest.raises(ValueError, match="catalog"):
        DbcDecoder(toyota, {"can.not_a_signal": ("ENGINE_RPM", "RPM")})
    with pytest.raises(KeyError):
        DbcDecoder(toyota, {"can.engine_rpm": ("NO_SUCH_MESSAGE", "RPM")})
    with pytest.raises(ValueError, match="catalog unit"):
        DbcDecoder(toyota, {"can.engine_rpm": ("WHEEL_SPEEDS", "WHEEL_SPEED_FL")})
    with pytest.raises(ValueError, match="exactly 1"):
        DbcDecoder(
            toyota,
            {"can.wheel_speed": MappedSignal("WHEEL_SPEEDS", ("WHEEL_SPEED_FL", "WHEEL_SPEED_FR"))},
        )
    with pytest.raises(ValueError, match="offset"):
        DbcDecoder(
            bmw,
            {"can.coolant_temp": MappedSignal("EngineData", ("TEMP_ENG", "TEMP_EOI"), "sum")},
        )
    with pytest.raises(ValueError, match="no SI conversion"):
        DbcDecoder(toyota, {"can.wheel_speed": ("KINEMATICS", "ACCEL_X")})


# Cross-check against comma's own processed arrays for the pinned example segment.

EXAMPLE_SEGMENT = "Example_1/b0c9d2329ad1606b|2018-08-02--08-34-47/40"


@pytest.mark.dataset
def test_decoder_matches_comma_processed_values_on_the_example_segment(toyota: Database) -> None:
    import numpy as np

    from photoncar.sources.comma2k19 import default_dataset_root

    can_dir = default_dataset_root() / EXAMPLE_SEGMENT / "processed_log" / "CAN"
    if not (can_dir / "raw_can" / "address").exists():
        pytest.skip("public dataset not fetched (make fetch-dataset)")
    raw = {k: np.load(can_dir / "raw_can" / k) for k in ("t", "src", "address", "data")}
    dec = DbcDecoder(toyota, COMMA2K19_TOYOTA_MAPPING, bus=0)
    got: dict[str, list[float]] = {name: [] for name in COMMA2K19_TOYOTA_MAPPING}
    for t, src, addr, payload in zip(
        raw["t"].tolist(),
        raw["src"].tolist(),
        raw["address"].tolist(),
        raw["data"].tolist(),
        strict=True,
    ):
        data = bytes(payload).ljust(8, b"\x00")  # numpy |S8 drops trailing zero bytes
        for s in dec.decode(CanFrame(round(t * 1e9), int(src), int(addr), False, 8, data)):
            got[s.signal].append(s.value)
    assert dec.decode_errors == 0
    wheel_ref = np.load(can_dir / "wheel_speed" / "value").mean(axis=1)
    steer_ref = np.load(can_dir / "steering_angle" / "value")
    assert len(got["can.wheel_speed"]) == len(wheel_ref) > 0
    assert len(got["can.steer_angle"]) == len(steer_ref) > 0
    # comma stores wheel speeds in m/s and the angle in degrees (tolerance 1e-9).
    assert np.max(np.abs(np.array(got["can.wheel_speed"]) - wheel_ref)) < 1e-9
    assert np.max(np.abs(np.degrees(got["can.steer_angle"]) - steer_ref)) < 1e-9
    rpm = np.array(got["can.engine_rpm"])
    assert rpm.size > 0 and 500.0 < float(np.median(rpm)) < 7000.0
