# BMW E90 PT-CAN, hand-built frames.


def test_e90_0xaa_engine_speed_is_raw_over_4(bmw: Database) -> None:
    dec = DbcDecoder(bmw, E90_PTCAN_MAPPING)
    data = bytes([0, 0, 0, 0, 0xF8, 0x1A, 0, 0])  # EngineSpeed raw 6904, little endian
    assert one(dec.decode(cf(0xAA, data)), "can.engine_rpm") == 1726.0


def test_e90_rpm_is_not_clamped_to_the_dbc_maximum(bmw: Database) -> None:
    msg = bmw.get_message_by_name("AccPedal")
    values = {s.name: 0 for s in msg.signals} | {"EngineSpeed": 8300}
    data = bmw.encode_message("AccPedal", values, strict=False)
    dec = DbcDecoder(bmw, E90_PTCAN_MAPPING)
    assert one(dec.decode(cf(0xAA, data)), "can.engine_rpm") == 8300.0


def test_e90_0x1d0_coolant_offset_minus_48(bmw: Database) -> None:
    dec = DbcDecoder(bmw, E90_PTCAN_MAPPING)
    data = bytes([0x96, 0, 0, 0, 0, 0, 0, 0])  # 150 - 48 = 102 degC
    assert one(dec.decode(cf(0x1D0, data)), "can.coolant_temp") == pytest.approx(
        102.0 + KELVIN_OFFSET, abs=1e-9
    )


def test_e90_coolant_through_cantools_encode(bmw: Database) -> None:
    msg = bmw.get_message_by_name("EngineData")
    values = {s.name: 0 for s in msg.signals} | {"TEMP_ENG": 90, "AIP_ENG": 1000}
    data = bmw.encode_message("EngineData", values, strict=False)
    dec = DbcDecoder(bmw, E90_PTCAN_MAPPING)
    assert one(dec.decode(cf(0x1D0, data)), "can.coolant_temp") == pytest.approx(363.15, abs=1e-9)


def test_e90_wheel_speed_mean_in_mps(bmw: Database) -> None:
    dec = DbcDecoder(bmw, E90_PTCAN_MAPPING)
    # FL, FR, RL, RR raw 1600, 1616, 1584, 1600 at 0.0625 km/h: 100, 101, 99, 100 km/h.
    data = bytes([0x40, 0x06, 0x50, 0x06, 0x30, 0x06, 0x40, 0x06])
    assert one(dec.decode(cf(0xCE, data)), "can.wheel_speed") == pytest.approx(100 / 3.6, abs=1e-9)


def test_e90_steering_angle_in_rad(bmw: Database) -> None:
    dec = DbcDecoder(bmw, E90_PTCAN_MAPPING)
    data = bytes([0x18, 0xFC, 0, 0, 0, 0, 0])  # SteeringPosition raw -1000
    expected = math.radians(-1000 * 0.0428316886)
    assert one(dec.decode(cf(0xC4, data)), "can.steer_angle") == pytest.approx(expected, abs=1e-12)


# comma2k19 2017 RAV4 powertrain.


def test_rav4_wheel_speeds_mean_known_answer(toyota: Database) -> None:
    dec = DbcDecoder(toyota, COMMA2K19_TOYOTA_MAPPING)
    # 15-bit big endian, 0.01 km/h, offset -67.67: FR 16767, FL 16769, RR 16767, RL 16765
    # = 100.00, 100.02, 100.00, 99.98 km/h. Mean 100.00 km/h = 27.777... m/s (tol 1e-9).
    data = bytes([0x41, 0x7F, 0x41, 0x81, 0x41, 0x7F, 0x41, 0x7D])
    assert one(dec.decode(cf(0xAA, data)), "can.wheel_speed") == pytest.approx(100 / 3.6, abs=1e-9)


def test_rav4_wheel_speeds_through_cantools_encode(toyota: Database) -> None:
    msg = toyota.get_message_by_name("WHEEL_SPEEDS")
    kph = {"WHEEL_SPEED_FL": 36.0, "WHEEL_SPEED_FR": 36.2, "WHEEL_SPEED_RL": 35.8}
    values = {s.name: 0 for s in msg.signals} | kph | {"WHEEL_SPEED_RR": 36.0}
    data = toyota.encode_message("WHEEL_SPEEDS", values)
    dec = DbcDecoder(toyota, COMMA2K19_TOYOTA_MAPPING)
    assert one(dec.decode(cf(0xAA, data)), "can.wheel_speed") == pytest.approx(10.0, abs=1e-9)


def test_rav4_engine_rpm_known_answer(toyota: Database) -> None:
    dec = DbcDecoder(toyota, COMMA2K19_TOYOTA_MAPPING)
    data = bytes([0x0A, 0x00, 0, 0, 0, 0, 0, 0])  # 2560 * 0.78125
    assert one(dec.decode(cf(0x1C4, data)), "can.engine_rpm") == 2000.0


@pytest.mark.parametrize(("angle", "fraction"), [(15.0, 0.3), (-45.0, -0.5), (0.0, 0.0)])
def test_rav4_steer_angle_is_angle_plus_fraction_in_rad(
    toyota: Database, angle: float, fraction: float
) -> None:
    msg = toyota.get_message_by_name("STEER_ANGLE_SENSOR")
    values = {s.name: 0 for s in msg.signals} | {"STEER_ANGLE": angle, "STEER_FRACTION": fraction}
    data = toyota.encode_message("STEER_ANGLE_SENSOR", values)
    dec = DbcDecoder(toyota, COMMA2K19_TOYOTA_MAPPING)
    assert one(dec.decode(cf(0x25, data)), "can.steer_angle") == pytest.approx(
        math.radians(angle + fraction), abs=1e-12
    )


