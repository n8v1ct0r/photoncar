def toyota() -> Database:
    return load_dbc(COMMA2K19_TOYOTA_DBC)


def cf(arb_id: int, data: bytes, *, bus: int = 0, t_ns: int = 1_000) -> CanFrame:
    return CanFrame(t_ns=t_ns, bus=bus, arb_id=arb_id, is_ext=False, dlc=len(data), data=data)


def one(samples: list[Sample], name: str) -> float:
    got = [s.value for s in samples if s.signal == name]
    assert len(got) == 1, samples
    return got[0]


# Vendoring.


def test_both_vendored_files_load() -> None:
    assert len(load_dbc(E90_PTCAN_DBC).messages) == 326
    assert len(load_dbc(COMMA2K19_TOYOTA_DBC).messages) == 58


def test_strictness_matches_source_record() -> None:
    cantools.database.load_file(VENDOR_DIR / E90_PTCAN_DBC, strict=True)
    with pytest.raises(UnsupportedDatabaseFormatError, match="overlapping"):
        cantools.database.load_file(VENDOR_DIR / COMMA2K19_TOYOTA_DBC, strict=True)
    source = (VENDOR_DIR / "SOURCE").read_text(encoding="utf-8")
    assert "loads with strict=True" in source
    assert "loads with strict=False" in source


def test_source_names_the_commit_and_hashes_match() -> None:
    source = (VENDOR_DIR / "SOURCE").read_text(encoding="utf-8")
    assert re.search(r"Commit: [0-9a-f]{40}", source)
    for name in (E90_PTCAN_DBC, "LICENSE"):
        digest = hashlib.sha256((VENDOR_DIR / name).read_bytes()).hexdigest()
        assert digest in source, name
    generated = hashlib.sha256((VENDOR_DIR / COMMA2K19_TOYOTA_DBC).read_bytes()).hexdigest()
    assert f"SHA-256 of the result: {generated}" in source
    license_text = (VENDOR_DIR / "LICENSE").read_text(encoding="utf-8")
    assert "Permission is hereby granted, free of charge" in license_text
    assert "Comma.ai" in license_text


def test_generated_file_has_the_generator_layout() -> None:
    text = (VENDOR_DIR / COMMA2K19_TOYOTA_DBC).read_text(encoding="utf-8")
    markers = [
        'CM_ "AUTOGENERATED FILE, DO NOT EDIT";',
        'CM_ "Imported file _toyota_2017.dbc starts here";',
        'CM_ "Imported file _toyota_adas_standard.dbc starts here";',
        'CM_ "toyota_new_mc_pt.dbc starts here";',
    ]
    positions = [text.index(m) for m in markers]
    assert positions == sorted(positions)
    assert 'CM_ "IMPORT' not in text


